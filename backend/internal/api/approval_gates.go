package api

import (
	"context"
	"errors"
	"net/http"
	"time"

	"icomic/backend/internal/db"
	"icomic/backend/internal/domain"
)

// commitApproval records an approval and stamps its entity in one repository commit. updatedAt is the entity's
// updated_at as the handler validated it, so an edit that lands in between is reported instead of blessed.
func (s *Server) commitApproval(w http.ResponseWriter, r *http.Request, a *domain.StageApproval, updatedAt time.Time) bool {
	err := s.Repo.ApproveStage(r.Context(), a, updatedAt)
	switch {
	case err == nil:
		return true
	case errors.Is(err, db.ErrConflict):
		writeError(w, http.StatusConflict, "Changed while approving; review the latest version and approve again")
	case errors.Is(err, db.ErrNotFound):
		writeError(w, http.StatusNotFound, "Not found")
	default:
		writeError(w, http.StatusInternalServerError, "Failed to save approval")
	}
	return false
}

// pageArtCurrent reports whether art generated by jobID started after the last edit of the page's panels,
// so an approval cannot bless art made from superseded text (SPEC 3.5, 3.6). Art without a recorded job
// cannot be dated and is accepted.
func (s *Server) pageArtCurrent(ctx context.Context, pg *domain.Page, jobID *string) (bool, error) {
	// Overlay pages letter their text after the art, so text edits do not invalidate it (docs/LETTERING.md).
	// Telling a text edit from a scene edit needs per-field edit times, which are not stored.
	if jobID == nil || pg.LetteringMode == "overlay" {
		return true, nil
	}
	job, err := s.JobService.GetJob(ctx, *jobID)
	if err != nil {
		return false, err
	}
	panels, err := s.Repo.ListPanels(ctx, pg.ChapterID)
	if err != nil {
		return false, err
	}
	onPage := make(map[string]bool, len(pg.PanelIDs))
	for _, id := range pg.PanelIDs {
		onPage[id] = true
	}
	for _, p := range panels {
		if onPage[p.ID] && p.UpdatedAt.After(job.CreatedAt) {
			return false, nil
		}
	}
	return true, nil
}

// chapterHasArt reports whether any page of the chapter carries generated art.
func (s *Server) chapterHasArt(ctx context.Context, chapterID string) (bool, error) {
	pages, err := s.Repo.ListPages(ctx, chapterID)
	if err != nil {
		return false, err
	}
	for _, pg := range pages {
		if pg.DraftImageURL != "" || pg.LineArtImageURL != "" || pg.PaintedPageImageURL != "" || pg.ColourImageURL != "" {
			return true, nil
		}
	}
	return false, nil
}

// requireCurrentArt answers 409 when the art was generated before the page's source was last edited.
func (s *Server) requireCurrentArt(w http.ResponseWriter, r *http.Request, pg *domain.Page, jobID *string, what string) bool {
	current, err := s.pageArtCurrent(r.Context(), pg, jobID)
	if err != nil {
		writeLookupError(w, err, "Generation job")
		return false
	}
	if !current {
		writeError(w, http.StatusConflict, "The "+what+" predates an edit to its panels; regenerate it before approving")
		return false
	}
	return true
}

// failReplacement ends a generation whose result could not replace the stored revision. Nothing was stored.
func (s *Server) failReplacement(w http.ResponseWriter, r *http.Request, jobID string, err error, message string) {
	if errors.Is(err, db.ErrArtExists) {
		message = "Generated page art exists; it cannot be regenerated"
	}
	_ = s.JobService.UpdateJobStatus(r.Context(), jobID, "failed", nil, &message)
	if errors.Is(err, db.ErrConflict) {
		writeError(w, http.StatusConflict, message)
		return
	}
	writeError(w, http.StatusInternalServerError, message)
}

// maxPanelsPerPage is the configured page capacity, defaulting to five (SPEC 3.5.1).
func (s *Server) maxPanelsPerPage() int {
	if s.MaxPanelsPerPage > 0 {
		return s.MaxPanelsPerPage
	}
	return 5
}
