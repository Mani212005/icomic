<script>
	import Icon from '#lib/design/Icon.svelte';
	import LetteringLayer from '../lettering/LetteringLayer.svelte';
	import { pollJob } from '#lib/api/jobPolling.js';
	import { EXPORT_FORMATS, PAGE_SIZES, EXPORT_PREVIEW_NOTES as NOTES, exportArtworkUrl, exportDrawsLettering, formatApiError } from '#lib/api/types.js';

	export let projectId = '';
	export let apiClient;
	export let pages = [];
	export let onComplete = () => {};

	let format = EXPORT_FORMATS.PDF;
	let pageSize = PAGE_SIZES.A4;
	let isExporting = false;
	let exportError = null;
	let exportWarnings = [];
	let currentExport = null;
	let downloadId = '';
	let isDownloading = false;
	// Stored lettering of the pages the export draws it on: page id -> layout, or null when it failed to load.
	let letterings = {};
	let brokenImages = {};
	$: pages.forEach(loadLettering);
	$: flaggedPages = new Set(exportWarnings.map((warning) => warning.page_number));

	async function loadLettering(page) {
		if (!exportDrawsLettering(page) || page.id in letterings || !apiClient?.getLettering) return;
		letterings[page.id] = undefined;
		try {
			letterings[page.id] = (await apiClient.getLettering(page.id)).lettering?.layout;
		} catch {
			letterings[page.id] = null;
		}
	}
	function markBroken(event) {
		brokenImages[event.currentTarget.dataset.url] = true;
	}
	const issueFlags = (layout) => [...new Set(layout.issues.map((issue) => issue.flag.replace(/_/g, ' ')))];
	$: downloadKind = format === EXPORT_FORMATS.PNG ? 'ZIP' : format.toUpperCase();

	async function handleExport() {
		if (!apiClient || !projectId) return;
		isExporting = true;
		exportError = '';
		exportWarnings = [];
		currentExport = null;
		downloadId = '';

		try {
			const res = await apiClient.exportProject(projectId, {
				format,
				page_size: pageSize
			});

			if (res.job) {
				await pollJob(apiClient, res.job.id, {
					intervalMs: 500,
					timeoutMs: 30000
				});
			}

			exportWarnings = res.warnings || [];

			if (res.export) {
				currentExport = res.export;
				downloadId = res.export.id;
				onComplete();
			}
		} catch (err) {
			exportError = formatApiError(err);
		} finally {
			isExporting = false;
		}
	}

	async function handleDownload() {
		isDownloading = true;
		exportError = null;
		try {
			await apiClient.saveExport(downloadId, downloadKind.toLowerCase());
		} catch (err) {
			exportError = formatApiError(err);
		} finally {
			isDownloading = false;
		}
	}
</script>

<div class="export-view">
	<header class="export-header">
		<h2>Export</h2>

	</header>

	<div class="compliance-notice">
		<div class="badge"><Icon name="info" size={18} /> Disclosure</div>
			<p>AI-generated by Meta; C2PA unverified.</p>
	</div>

	<div class="options-grid">
		<div class="option-card">
			<label for="format-select">Format</label>
			<select id="format-select" bind:value={format}>
				<option value={EXPORT_FORMATS.PDF}>PDF</option>
				<option value={EXPORT_FORMATS.PNG}>PNG (.zip)</option>
			</select>

		</div>

		<div class="option-card">
			<label for="pagesize-select">Size</label>
			<select id="pagesize-select" bind:value={pageSize} disabled={format === EXPORT_FORMATS.PNG}>
				{#if format === EXPORT_FORMATS.PNG}
					<option value={pageSize}>Original size</option>
				{:else}
					<option value={PAGE_SIZES.A4}>A4 (210 × 297 mm)</option>
					<option value={PAGE_SIZES.US_LETTER}>US Letter (8.5 × 11 in)</option>
					<option value={PAGE_SIZES.CUSTOM}>Custom (6.625 × 10.25 in)</option>
				{/if}
			</select>
		</div>
	</div>

	<div class="preview-section">
		<h3>Pages ({pages.length})</h3>
		<div class="pages-strip">
			{#if pages.length === 0}
				<div class="empty-pages"><Icon name="panels" size={40} />None.</div>
			{:else}
				{#each pages as page, i (page.id)}
					{@const url = exportArtworkUrl(page)}
					{@const layout = letterings[page.id]}
					<figure class="export-page">
						<div class="export-art">
							{#if url && !brokenImages[url]}
								<img src={url} alt={`Page ${i + 1}`} on:error={markBroken} data-url={url} draggable="false" />
								{#if layout}<LetteringLayer {layout} idPrefix={`export-${page.id}`} />{/if}
							{:else}
								<div class="export-art-missing"><Icon name="warning" size={20} label={NOTES.noArtwork} /></div>
							{/if}
						</div>
						<figcaption>
							Page {i + 1}
							{#if layout === null}<Icon name="warning" size={14} label={NOTES.letteringFailed} />{/if}
							{#if layout && issueFlags(layout).length}<Icon name="warning" size={14} label={NOTES.review(issueFlags(layout))} />{/if}
							{#if flaggedPages.has(i + 1)}<Icon name="warning" size={14} label={NOTES.flagged} />{/if}
						</figcaption>
					</figure>
				{/each}
			{/if}
		</div>
	</div>

	{#if exportError}
		<div class="error-banner" role="alert">
			<Icon name="warning" size={18} />
			<div>
				<strong>{exportError.title}</strong>
				<p>{exportError.message}</p>
				{#if exportError.action}<p class="error-action">Next: {exportError.action}</p>{/if}
			</div>
		</div>
	{/if}

	{#if exportWarnings.length}
		<div class="error-banner" role="alert">
			<Icon name="warning" size={18} />
			<div>
				{#each exportWarnings as warning}
					<p>Page {warning.page_number}: {warning.message}</p>
				{/each}
			</div>
		</div>
	{/if}

	<div class="export-actions">
		<button
			class="export-btn"
			aria-label={isExporting ? `Exporting ${format.toUpperCase()}` : `Export ${format.toUpperCase()}`}
			on:click={handleExport}
			disabled={isExporting}
			aria-busy={isExporting}
		>
			{#if isExporting}
				<span class="spinner"></span> Exporting {format.toUpperCase()}...
			{:else}
				<Icon name="export" size={18} /> Export {format.toUpperCase()}
			{/if}
		</button>

		{#if downloadId}
			<button class="export-btn download-link" on:click={handleDownload} disabled={isDownloading} aria-busy={isDownloading}>
				<Icon name="download" size={18} /> Download {downloadKind}
			</button>
		{/if}
	</div>
</div>
