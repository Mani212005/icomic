def _local_env(monkeypatch, directory):
    for name in ("LANGUAGE", "IMAGE", "VISION", "QUEUE", "CLOCK", "MEDIA_FETCH"):
        monkeypatch.setenv("ADAPTER_" + name, "fake")
    monkeypatch.setenv("ADAPTER_STORAGE", "local")
    monkeypatch.setenv("LOCAL_STORAGE_DIR", str(directory))
    monkeypatch.delenv("ICOMIC_E2E_FAKE_STORAGE_DIR", raising=False)
    monkeypatch.delenv("ICOMIC_E2E_RUN_ID", raising=False)
    monkeypatch.delenv("ICOMIC_E2E_LIVE", raising=False)
    monkeypatch.setenv("STORAGE_BASE_URL", "http://ai:8000/storage/fake")


def test_local_storage_survives_an_ai_restart_without_any_e2e_run_marker(tmp_path, monkeypatch):
    """Generated bytes written by one AI process are served by the next one."""
    _local_env(monkeypatch, tmp_path)
    key = "pages/page-1/painted-job-1.webp"
    original = image_bytes("painted page one")
    first = build_adapters_from_env()
    url = first.storage.put(key, original, "image/webp")
    assert url == "http://ai:8000/storage/fake/" + key
    del first  # The first AI process is gone; only the mounted volume remains.

    with TestClient(create_app(build_adapters_from_env())) as client:
        served = client.get("/storage/fake/" + key)
        assert served.status_code == 200
        assert served.content == original
        assert served.headers["content-type"] == "image/webp"
        assert client.head("/storage/fake/" + key).status_code == 200
        assert client.get("/storage/fake/pages/missing.webp").status_code == 404


def test_local_storage_reads_always_hit_the_volume(tmp_path):
    first = LocalStorageAdapter(tmp_path, base_url="http://ai:8000/storage/fake")
    other = LocalStorageAdapter(tmp_path, base_url="http://ai:8000/storage/fake")
    url = first.put("a/b.png", b"one", "image/png")
    assert other.get(url) == b"one" and other.get_content_type(url) == "image/png"
    other.delete(url)
    with pytest.raises(KeyError):
        first.get(url)
    assert first.get_content_type(url) is None


def test_local_storage_matches_the_checkpoint_layout_of_the_fake_adapter(tmp_path):
    """Directories written in checkpoint mode stay readable, so saved URLs keep working."""
    old = FakeStorageAdapter(base_url="http://ai:8000/storage/fake", directory=tmp_path)
    url = old.put("characters/nia/reference.webp", b"nia", "image/webp")
    local = LocalStorageAdapter(tmp_path, base_url="http://ai:8000/storage/fake")
    assert local.get(url) == b"nia" and local.get_content_type(url) == "image/webp"


def test_local_storage_refuses_traversal_and_missing_configuration(tmp_path, monkeypatch):
    storage = LocalStorageAdapter(tmp_path / "volume")
    with pytest.raises(ValueError):
        storage.put("../escape", b"x", "text/plain")
    assert not (tmp_path / "escape").exists()
    monkeypatch.setenv("ADAPTER_STORAGE", "local")
    monkeypatch.delenv("LOCAL_STORAGE_DIR", raising=False)
    with pytest.raises(ValueError, match="LOCAL_STORAGE_DIR"):
        get_storage_adapter()


def test_local_storage_never_silently_replaces_an_e2e_checkpoint(tmp_path, monkeypatch):
    _local_env(monkeypatch, tmp_path / "volume")
    monkeypatch.setenv("ICOMIC_E2E_FAKE_STORAGE_DIR", str(tmp_path / "checkpoint"))
    with pytest.raises(ValueError, match="ICOMIC_E2E_FAKE_STORAGE_DIR"):
        get_storage_adapter()
